inline void check1(Reporter& report) {
    heading(1, "factorial<unsigned long long> vs factorial<BigInt>, n = 1..25");
    std::cout << "   n  " << std::left << std::setw(22) << "unsigned long long"
              << "  BigInt\n";

    bool ullOk = true, bigOk = true;
    unsigned firstDiff = 0;
    for (const FactRow& row : kFactorials) {
        unsigned long long u = factorial<unsigned long long>(row.n);
        std::string b = factorial<BigInt>(row.n).toString();
        bool differ = std::to_string(u) != b;
        if (differ && firstDiff == 0) firstDiff = row.n;
        if (u != row.wrapped) ullOk = false;
        if (b != row.exact) bigOk = false;
        std::cout << "  " << std::right << std::setw(2) << row.n << "  "
                  << std::left << std::setw(22) << u << "  " << b
                  << (differ ? "   <-- differ" : "") << '\n';
    }
    report("1a", "factorial<unsigned long long> matches expected values", ullOk);
    report("1b", "factorial<BigInt> matches exact n! for n = 1..25", bigOk);
    report("1c", "first n where the two differ", firstDiff == 21,
           "21", firstDiff == 0 ? "(none)" : std::to_string(firstDiff));
}

