// Runs `action` and reports whether it threw exactly the expected type.
template <typename Expected, typename Action>
void expectThrow(Reporter& report, const std::string& id,
                 const std::string& what, Action action) {
    const std::string expectedName =
        std::same_as<Expected, std::invalid_argument> ? "std::invalid_argument"
                                                      : "std::out_of_range";
    try {
        action();
        report(id, what, false, expectedName, "no exception");
    } catch (const Expected&) {
        report(id, what, true, expectedName, expectedName);
    } catch (const std::exception& e) {
        report(id, what, false, expectedName,
               std::string("a different exception: ") + e.what());
    } catch (...) {
        report(id, what, false, expectedName, "a non-standard exception");
    }
}

