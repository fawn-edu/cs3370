// ---------------------------------------------------------------------
// Heap accounting.
// ---------------------------------------------------------------------
namespace cs3370_perf_detail {
inline std::size_t liveBytes   = 0;   // bytes currently allocated
inline std::size_t peakBytes   = 0;   // high-water mark of liveBytes
inline std::size_t allocations = 0;   // number of calls to operator new

// Each block carries a small header recording its requested size, so
// operator delete knows how many bytes are being returned.
struct alignas(std::max_align_t) BlockHeader {
    std::size_t size;
};
}  // namespace cs3370_perf_detail

// Replacement global allocation functions. These may NOT be declared
// inline (the language forbids it), which is why this header must be
// included in exactly one .cpp file.
void* operator new(std::size_t size) {
    namespace d = cs3370_perf_detail;
    void* raw = std::malloc(sizeof(d::BlockHeader) + size);
    if (raw == nullptr) throw std::bad_alloc{};
    d::BlockHeader* header = static_cast<d::BlockHeader*>(raw);
    header->size = size;
    d::liveBytes += size;
    if (d::liveBytes > d::peakBytes) d::peakBytes = d::liveBytes;
    ++d::allocations;
    return header + 1;
}

void operator delete(void* p) noexcept {
    namespace d = cs3370_perf_detail;
    if (p == nullptr) return;
    d::BlockHeader* header = static_cast<d::BlockHeader*>(p) - 1;
    d::liveBytes -= header->size;
    std::free(header);
}

void operator delete(void* p, std::size_t) noexcept { ::operator delete(p); }
void* operator new[](std::size_t size) { return ::operator new(size); }
void operator delete[](void* p) noexcept { ::operator delete(p); }
void operator delete[](void* p, std::size_t) noexcept { ::operator delete(p); }

