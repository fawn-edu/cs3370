struct Reporter {
    int passed = 0;
    int failed = 0;

    void operator()(const std::string& id, const std::string& what, bool ok,
                    const std::string& expected = "true",
                    const std::string& got = "false") {
        (ok ? passed : failed) += 1;
        std::cout << (ok ? "  [PASS] " : "  [FAIL] ")
                  << std::left << std::setw(5) << id << what << '\n';
        if (!ok) {
            std::cout << "           expected: " << expected << '\n'
                      << "           got:      " << got << '\n';
        }
    }
};

inline void heading(int n, const std::string& title) {
    std::cout << "\n=== Check " << n << ": " << title << " ===\n";
}

inline std::string yesNo(bool b) { return b ? "true" : "false"; }

// ---------------------------------------------------------------------
// Small helpers built ONLY from BigInt's public interface.
// ---------------------------------------------------------------------
inline long long digitSum(const BigInt& b) {
    long long sum = 0;
    for (std::size_t i = 0; i < b.digitCount(); ++i)
        sum += b[i];
    return sum;
}

inline std::size_t trailingZeros(const BigInt& b) {
    std::size_t count = 0;
    while (count < b.digitCount() && b[count] == 0)
        ++count;
    return count;
}

// operator[], digitCount(), and toString() must all agree.
inline bool digitsAgreeWithString(const BigInt& b) {
    std::string s = b.toString();
    if (!s.empty() && s[0] == '-') s.erase(0, 1);
    if (s.size() != b.digitCount()) return false;
    for (std::size_t i = 0; i < s.size(); ++i)
        if (b[i] != s[s.size() - 1 - i] - '0') return false;
    return true;
}

